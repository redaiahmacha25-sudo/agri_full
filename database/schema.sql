CREATE TYPE entity_type AS ENUM
('sell_request','service_request');
CREATE TYPE notification_type AS ENUM
('info','success','warning','error');
CREATE TYPE target_role AS ENUM
( 'all','farmer','employee','admin');
-- ============================================================
-- REMARKS TABLE
-- ============================================================
CREATE TABLE remarks
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type entity_type NOT NULL,
    entity_id INTEGER NOT NULL,
    message TEXT NOT NULL,
    created_by INTEGER NOT NULL,
    is_internal BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_remarks_user
        FOREIGN KEY(created_by)
        REFERENCES users(id)
        ON DELETE CASCADE
);
-- ============================================================
-- REMARKS INDEXES
-- ============================================================
CREATE INDEX idx_remarks_entity
ON remarks(entity_type, entity_id);
CREATE INDEX idx_remarks_created_by
ON remarks(created_by);
-- ============================================================
-- NOTIFICATIONS TABLE
-- ============================================================
CREATE TABLE notifications
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    type notification_type DEFAULT 'info',
    is_read BOOLEAN DEFAULT FALSE,
    link VARCHAR(200),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_user
        FOREIGN KEY(user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);
-- ============================================================
-- NOTIFICATION INDEXES
-- ============================================================
CREATE INDEX idx_notifications_user
ON notifications(user_id);
CREATE INDEX idx_notifications_read
ON notifications(is_read);
-- ============================================================
-- ANNOUNCEMENTS TABLE
-- ============================================================
CREATE TABLE announcements
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    target_role target_role DEFAULT 'all',
    is_active BOOLEAN DEFAULT TRUE,
    created_by INTEGER NOT NULL,
    expires_at DATE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_announcements_user
        FOREIGN KEY(created_by)
        REFERENCES users(id)
        ON DELETE CASCADE
);
-- ============================================================
-- ANNOUNCEMENTS INDEXES
-- ============================================================
CREATE INDEX idx_announcements_role
ON announcements(target_role);
CREATE INDEX idx_announcements_active
ON announcements(is_active);
