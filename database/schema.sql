-- AGRICONNECT DATABASE SCHEMA (POSTGRESQL)
--============================================================
-- ============================================================
-- DROP TABLES (Optional)
-- ============================================================
DROP TABLE IF EXISTS crops CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TYPE IF EXISTS user_role CASCADE;
DROP TYPE IF EXISTS crop_category CASCADE;
DROP TYPE IF EXISTS crop_season CASCADE;
-- ============================================================
-- ENUM TYPES
-- ============================================================
CREATE TYPE user_role AS ENUM ('farmer','employee','admin');
CREATE TYPE crop_category AS ENUM ('cereal','pulse','oilseed','vegetable','fruit', 'other');
CREATE TYPE crop_season AS ENUM ('kharif','rabi','zaid','all');
-- ============================================================
-- FUNCTION FOR updated_at
-- ============================================================
CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS TRIGGER AS
$$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$
LANGUAGE plpgsql;
-- ============================================================
-- USERS TABLE
-- ============================================================
CREATE TABLE users
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) UNIQUE NOT NULL,
    email VARCHAR(100),
    password_hash VARCHAR(255) NOT NULL,
    role user_role NOT NULL DEFAULT 'farmer',
    aadhar_number VARCHAR(12),
    village VARCHAR(100),
    district VARCHAR(100),
    state VARCHAR(100) DEFAULT 'Andhra Pradesh',
    pincode VARCHAR(6),
    bank_account VARCHAR(20),
    ifsc_code VARCHAR(11),
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);
-- ============================================================
-- INDEXES
-- ============================================================
CREATE INDEX idx_users_role
ON users(role);
CREATE INDEX idx_users_phone
ON users(phone);
CREATE INDEX idx_users_district
ON users(district);
-- ============================================================
-- UPDATE TRIGGER
-- ============================================================
CREATE TRIGGER trg_users_timestamp
BEFORE UPDATE
ON users
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();
-- ============================================================
-- CROPS TABLE
-- ============================================================
CREATE TABLE crops
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    name_telugu VARCHAR(100),
    category crop_category DEFAULT 'cereal',
    govt_price NUMERIC(10,2) NOT NULL,
    unit VARCHAR(20) DEFAULT 'quintal',
    season crop_season DEFAULT 'all',
    is_active BOOLEAN DEFAULT TRUE,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INTEGER,
    CONSTRAINT fk_crop_user
        FOREIGN KEY(updated_by)
        REFERENCES users(id)
        ON DELETE SET NULL
);
COMMENT ON COLUMN crops.govt_price
IS 'Government MSP Price Per Quintal';
-- ============================================================
-- CROPS INDEXES
-- ============================================================
CREATE INDEX idx_crop_name
ON crops(name);
CREATE INDEX idx_crop_category
ON crops(category);
CREATE INDEX idx_crop_season
ON crops(season);
CREATE INDEX idx_crop_active
ON crops(is_active);
