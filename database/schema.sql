-- ============================================================
-- SELL REQUESTS TABLE
-- ============================================================
CREATE TABLE sell_requests
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INTEGER NOT NULL,
    crop_id INTEGER NOT NULL,
    quantity NUMERIC(10,2) NOT NULL,
    govt_price NUMERIC(10,2),
    expected_amount NUMERIC(12,2),
    image_url VARCHAR(500),
    geo_lat NUMERIC(10,8),
    geo_lng NUMERIC(11,8),
    village VARCHAR(100),
    harvest_date DATE,
    notes TEXT,
    status sell_status DEFAULT 'pending',
    verified_by INTEGER,
    verified_at TIMESTAMP,
    rejection_reason TEXT,
    approved_by INTEGER,
    approved_at TIMESTAMP,
    procurement_date DATE,
    payment_status payment_status DEFAULT 'pending',
    payment_amount NUMERIC(12,2),
    transaction_ref VARCHAR(100),
    payment_date TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_sell_farmer
        FOREIGN KEY(farmer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_sell_crop
        FOREIGN KEY(crop_id)
        REFERENCES crops(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_verified_by
        FOREIGN KEY(verified_by)
        REFERENCES users(id)
        ON DELETE SET NULL,
    CONSTRAINT fk_approved_by
        FOREIGN KEY(approved_by)
        REFERENCES users(id)
        ON DELETE SET NULL
);
-- ============================================================
-- INDEXES
-- ============================================================
CREATE INDEX idx_sell_farmer
ON sell_requests(farmer_id);
CREATE INDEX idx_sell_status
ON sell_requests(status);
CREATE INDEX idx_sell_crop
ON sell_requests(crop_id);
CREATE INDEX idx_sell_created
ON sell_requests(created_at);
-- ============================================================
-- UPDATE TRIGGER
-- ============================================================
CREATE TRIGGER trg_sell_requests_timestamp
BEFORE UPDATE
ON sell_requests
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();
